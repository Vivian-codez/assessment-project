"""Draft Grade database model."""

# Import datetime class for UTC timestamp tracking
from datetime import datetime
# Import SQLAlchemy Column, column types (String, Float, DateTime, ForeignKey, Text, JSON)
from sqlalchemy import Column, String, Float, DateTime, ForeignKey, Text, JSON
# Import relationship construct to map links between DraftGrade, Submission, and Instructor
from sqlalchemy.orm import relationship

# Import declarative Base class from app.core.database
from app.core.database import Base


# Database model representing AI-suggested grades pending teacher verification and approval
class DraftGrade(Base):
    # Specify target physical table name in PostgreSQL
    __tablename__ = "draft_grades"

    # Alphanumeric unique identifier for draft grade acting as primary key
    id = Column(String(64), primary_key=True, index=True)
    # Foreign key referencing parent submission (unique constraint ensures exactly 1 grade per submission)
    submission_id = Column(String(64), ForeignKey("submissions.id", ondelete="CASCADE"), unique=True, nullable=False)

    # Initial score recommended by the AI model based on rubric criteria
    suggested_score = Column(Float, nullable=True, default=0.0)
    # Calculated total points aggregate
    total_score = Column(Float, nullable=True)
    # Maximum obtainable point threshold (defaults to 100.0)
    max_score = Column(Float, nullable=True, default=100.0)
    # Official final grade stamped and awarded only upon formal teacher approval
    final_score = Column(Float, nullable=True)  # Populated only upon Teacher Approval

    # Structured rubric breakdown:
    # [{"criterion_name": "Understanding", "score": 25, "max": 30, "rationale": "..."}]
    # JSON array storing scores, weights, and rationales for each rubric criterion
    criteria_scores = Column(JSON, nullable=False, default=list)
    # JSON array storing detailed criterion breakdowns and level descriptors
    criteria_breakdown = Column(JSON, nullable=True, default=list)

    # 3-Way Plagiarism report:
    # {"peer_to_peer_score": 0.0, "public_source_score": 0.0, "ai_probability": 0.0, "flagged_matches": []}
    # JSON document storing 3-way plagiarism results (peer, web, and AI probability)
    plagiarism_report = Column(JSON, nullable=True, default=dict)

    # Automated qualitative feedback generated by Google Gemini model
    ai_feedback = Column(Text, nullable=True)
    # Customized teacher notes, corrections, and personalized feedback
    teacher_feedback = Column(Text, nullable=True)
    # Consolidated feedback text displayed on final grade reports
    feedback = Column(Text, nullable=True)

    # Status: pending, flagged, approved
    # Approval state of the grade indexed for teacher review queues
    status = Column(String(32), default="pending", index=True)

    # UTC timestamp recording when the teacher approved the grade
    approved_at = Column(DateTime, nullable=True)
    # Foreign key referencing the instructor who reviewed and approved the grade
    approved_by_id = Column(String(64), ForeignKey("instructors.id", ondelete="SET NULL"), nullable=True)
    # Specific Gemini model identifier used for evaluation generation (e.g. 'gemini-2.5-flash')
    ai_model = Column(String(64), default="gemini-2.5-flash")

    # UTC timestamp when the evaluation draft was created
    created_at = Column(DateTime, default=datetime.utcnow)
    # UTC timestamp when the grade record was last modified
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    # Relationships
    # One-to-one relationship mapping the target submission
    submission = relationship("Submission", back_populates="draft_grade")
    # Many-to-one relationship mapping the approving instructor
    approved_by = relationship("Instructor")
