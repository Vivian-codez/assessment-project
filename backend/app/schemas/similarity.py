# Module docstring explaining that this file defines schemas for similarity and peer cross-submission plagiarism
"""Similarity and Peer-to-Peer Cross-Submission Plagiarism Schemas."""

# Import typing utilities for lists and optional fields
from typing import List, Optional
# Import Pydantic base model, field helper, and configuration dictionary
from pydantic import BaseModel, Field, ConfigDict


# Schema representing basic student identity references in peer comparisons
class StudentRef(BaseModel):
    # Unique identifier of the student
    id: str
    # Plaintext decrypted student name
    name: str
    # Student roll number or identifier
    roll: str


# Schema representing a pairwise comparison between two student submissions
class SimilarityPairResponse(BaseModel):
    # Configure model to support field aliases and ORM attribute reading
    model_config = ConfigDict(populate_by_name=True, from_attributes=True)

    # Unique string identifier for the matched comparison pair
    pair_id: str
    # Display name or identifier for Student A
    a: str = Field(description="Student A display name")
    # Display name or identifier for Student B
    b: str = Field(description="Student B display name")
    # Structured student reference object for Student A
    student_a: Optional[StudentRef] = None
    # Structured student reference object for Student B
    student_b: Optional[StudentRef] = None
    # Percentage similarity score between the pair, aliased from 'similarity'
    score: float = Field(alias="similarity", description="Similarity score percentage")
    # Qualitative status flag (e.g., 'Within range' or 'Flagged for Review')
    status: str = "Within range"
    # List of verbatim matching sentences or phrases found in both papers
    matching_phrases: List[str] = Field(default_factory=list)
    # Estimated probability that the text was generated by AI, defaulting to 0.0
    ai_content_probability: float = 0.0


# Schema representing an aggregate summary of similarity check results across a batch
class SimilarityCheckOverviewResponse(BaseModel):
    # Numerical similarity threshold used for flagging (e.g. 90.0%)
    threshold: float = 90.0
    # Total count of submissions submitted in the assignment
    total_submissions: int
    # Total count of submissions analyzed for similarity
    checked: int
    # Count of submission pairs exceeding the potential similarity warning threshold
    potential_similarity: int
    # Count of submission pairs exceeding the high critical similarity threshold
    high_similarity: int
    # List of pairwise detailed similarity comparisons
    pairs: List[SimilarityPairResponse]
